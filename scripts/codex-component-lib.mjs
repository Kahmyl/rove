import { execFile as execFileCallback } from "node:child_process";
import { createHash } from "node:crypto";
import {
  access,
  chmod,
  copyFile,
  mkdir,
  open,
  readFile,
  rename,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, isAbsolute, join, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFile = promisify(execFileCallback);
export const repositoryRoot = resolve(
  dirname(fileURLToPath(import.meta.url)),
  "..",
);
export const componentManifestPath = join(
  repositoryRoot,
  "apps/companion/src/main/codex/approved-components.json",
);
export const compiledSchemaBindingsPath = join(
  repositoryRoot,
  "apps/companion/src/main/codex/compiled-schema-bindings.json",
);

export async function readComponentManifest(path = componentManifestPath) {
  return JSON.parse(await readFile(path, "utf8"));
}

export async function readCompiledSchemaBindings(
  path = compiledSchemaBindingsPath,
) {
  return JSON.parse(await readFile(path, "utf8"));
}

export function selectedComponent(manifest) {
  const id = manifest.selection;
  const component = manifest.components?.find((entry) => entry.id === id);
  if (!component)
    throw new Error(
      `Approved Codex component selection ${String(id)} is missing.`,
    );
  if (!["qualified", "retained-qualified"].includes(component.status))
    throw new Error(
      `Approved Codex component ${component.id} has not passed qualification.`,
    );
  return component;
}

export function compiledSchemaBinding(component, registry) {
  const binding = registry.bindings?.find(
    (entry) => entry.componentId === component.id,
  );
  if (!binding)
    throw new Error(
      `Codex component ${component.id} has no compiled schema binding.`,
    );
  if (
    binding.filename !== component.schema?.filename ||
    binding.sha256 !== component.schema?.sha256 ||
    binding.compiledRuntimeSha256 !== component.schema?.compiledRuntimeSha256 ||
    binding.aggregateSha256 !== component.schema?.aggregateSha256 ||
    binding.generatedTsAggregateSha256 !==
      component.schema?.generatedTsAggregateSha256 ||
    binding.historyMode !== component.historyMode
  )
    throw new Error(
      `Codex component ${component.id} does not match its compiled schema binding.`,
    );
  return binding;
}

export async function verifyCompiledSchemaBinding(
  component,
  registry,
  schemaRoot = join(repositoryRoot, "apps/companion/src/main/codex"),
) {
  const binding = compiledSchemaBinding(component, registry);
  const path = join(schemaRoot, binding.filename);
  const digest = await sha256(path).catch(() => {
    throw new Error(
      `Compiled Codex schema is unavailable for ${component.id}: ${path}`,
    );
  });
  if (digest !== binding.sha256)
    throw new Error(
      `Compiled Codex schema digest does not match component ${component.id}.`,
    );
  const catalog = JSON.parse(await readFile(path, "utf8"));
  if (
    typeof catalog.generatedBy !== "string" ||
    !catalog.generatedBy.includes(component.cliVersion)
  )
    throw new Error(
      `Compiled Codex schema was not generated by ${component.cliVersion}.`,
    );
  if (
    catalog.generatedTsAggregateSha256 !== binding.generatedTsAggregateSha256 ||
    binding.generatedTsAggregateSha256 !==
      component.schema.generatedTsAggregateSha256
  )
    throw new Error(
      `Compiled Codex schema aggregate does not match component ${component.id}.`,
    );
  return { binding, path, digest };
}

export function promoteComponentSelection(manifest, componentId, registry) {
  const component = manifest.components?.find(
    (entry) => entry.id === componentId,
  );
  if (
    !component ||
    !["qualified", "retained-qualified"].includes(component.status)
  )
    throw new Error(
      `Codex component ${componentId} has not passed qualification.`,
    );
  compiledSchemaBinding(component, registry);
  return {
    ...manifest,
    selection: componentId,
  };
}

export async function writeComponentManifestAtomically(
  path,
  manifest,
  { onDurabilityStep = () => {} } = {},
) {
  const temporary = `${path}.promoting-${process.pid}`;
  try {
    const temporaryHandle = await open(temporary, "w", 0o600);
    try {
      await temporaryHandle.writeFile(
        `${JSON.stringify(manifest, null, 2)}\n`,
      );
      await temporaryHandle.sync();
      onDurabilityStep("temporary-synced");
    } finally {
      await temporaryHandle.close();
    }
  } catch (error) {
    await rm(temporary, { force: true });
    throw error;
  }
  try {
    await rename(temporary, path);
    onDurabilityStep("renamed");
    const parentHandle = await open(dirname(path), "r");
    try {
      await parentHandle.sync();
      onDurabilityStep("parent-synced");
    } finally {
      await parentHandle.close();
    }
  } catch (error) {
    await rm(temporary, { force: true });
    throw error;
  }
}

export function defaultManagedCodexRoot() {
  const override = process.env.ROVE_CODEX_COMPONENTS_HOME?.trim();
  if (override) {
    if (!isAbsolute(override))
      throw new Error("ROVE_CODEX_COMPONENTS_HOME must be an absolute path.");
    return resolve(override);
  }
  if (process.platform === "darwin")
    return join(
      homedir(),
      "Library",
      "Application Support",
      "Rove",
      "components",
      "codex",
    );
  if (process.platform === "win32")
    return join(
      process.env.LOCALAPPDATA ?? homedir(),
      "Rove",
      "components",
      "codex",
    );
  return join(
    process.env.XDG_DATA_HOME ?? join(homedir(), ".local", "share"),
    "rove",
    "components",
    "codex",
  );
}

export function componentPaths(root, component) {
  const directory = join(root, component.id);
  return {
    directory,
    executable: join(directory, component.executable.filename),
    codeModeHost: join(directory, component.codeModeHost.filename),
    receipt: join(directory, "qualification.json"),
  };
}

export function qualificationEvidencePath(component) {
  return join(
    repositoryRoot,
    "artifacts",
    "codex-component-qualification",
    component.id,
    "qualification.json",
  );
}

export function createQualificationReceipt(component, candidate, qualifiedAt) {
  return {
    schemaVersion: 1,
    qualifiedAt,
    componentId: component.id,
    executable: {
      sha256: candidate.executable.sha256,
      bytes: candidate.executable.bytes,
    },
    codeModeHost: {
      sha256: candidate.codeModeHost.sha256,
      bytes: candidate.codeModeHost.bytes,
    },
    schema: component.schema,
    historyMode: component.historyMode,
    compatibility: {
      schemaBindingVerified: true,
      isolatedAppServerLifecycle: true,
      mcpBoundary: true,
      liveModelTurn: false,
    },
  };
}

export async function verifyQualificationReceipt(path, component) {
  const receipt = await readFile(path, "utf8")
    .then(JSON.parse)
    .catch(() => {
      throw new Error(
        `Immutable qualification receipt is unavailable for ${component.id}: ${path}`,
      );
    });
  const exact =
    receipt.schemaVersion === 1 &&
    typeof receipt.qualifiedAt === "string" &&
    Number.isFinite(Date.parse(receipt.qualifiedAt)) &&
    receipt.componentId === component.id &&
    receipt.executable?.sha256 === component.executable.sha256 &&
    (component.executable.bytes === undefined ||
      receipt.executable?.bytes === component.executable.bytes) &&
    receipt.codeModeHost?.sha256 === component.codeModeHost.sha256 &&
    receipt.codeModeHost?.bytes === component.codeModeHost.bytes &&
    receipt.schema?.filename === component.schema.filename &&
    receipt.schema?.sha256 === component.schema.sha256 &&
    receipt.schema?.compiledRuntimeSha256 ===
      component.schema.compiledRuntimeSha256 &&
    receipt.schema?.aggregateSha256 === component.schema.aggregateSha256 &&
    receipt.schema?.generatedTsAggregateSha256 ===
      component.schema.generatedTsAggregateSha256 &&
    receipt.historyMode === component.historyMode &&
    receipt.compatibility?.schemaBindingVerified === true &&
    receipt.compatibility?.isolatedAppServerLifecycle === true &&
    receipt.compatibility?.mcpBoundary === true &&
    receipt.compatibility?.liveModelTurn === false;
  if (!exact)
    throw new Error(
      `Immutable qualification receipt does not match component ${component.id} and its required compatibility evidence.`,
    );
  return receipt;
}

export async function verifyInstalledQualificationReceipt(
  directory,
  component,
) {
  return verifyQualificationReceipt(
    componentPaths(dirname(directory), component).receipt,
    component,
  );
}

export async function verifyPromotableComponentSet(
  manifest,
  registry,
  managedRoot = defaultManagedCodexRoot(),
  schemaRoot = join(repositoryRoot, "apps/companion/src/main/codex"),
) {
  const qualified = manifest.components?.filter((entry) =>
    ["qualified", "retained-qualified"].includes(entry.status),
  );
  if (!qualified?.length)
    throw new Error("No qualified Codex components are registered.");
  for (const component of qualified) {
    await verifyCompiledSchemaBinding(component, registry, schemaRoot);
    const directory = componentPaths(managedRoot, component).directory;
    await verifyComponentDirectory(directory, component);
    await verifyInstalledQualificationReceipt(directory, component);
  }
}

export async function sha256(path) {
  return createHash("sha256")
    .update(await readFile(path))
    .digest("hex");
}

export async function probeCodexVersion(path) {
  const { stdout, stderr } = await execFile(path, ["--version"], {
    timeout: 5_000,
  });
  const match = `${stdout}\n${stderr}`.match(/codex(?:-cli)?\s+(\S+)/i);
  if (!match?.[1])
    throw new Error("Codex version probe returned an unrecognized response.");
  return match[1];
}

async function verifyFile(path, expected, label) {
  await access(path).catch(() => {
    throw new Error(`${label} is unavailable: ${path}`);
  });
  const details = await stat(path);
  if (!details.isFile() || (details.mode & 0o111) === 0)
    throw new Error(`${label} is not an executable file: ${path}`);
  if (expected.bytes !== undefined && details.size !== expected.bytes)
    throw new Error(`${label} size does not match ${expected.bytes}.`);
  const digest = await sha256(path);
  if (digest !== expected.sha256)
    throw new Error(
      `${label} digest does not match approved component ${expected.sha256}.`,
    );
  return { path, sha256: digest, bytes: details.size };
}

export async function verifyComponentDirectory(directory, component) {
  if (
    process.platform !== component.nodePlatform ||
    process.arch !== component.architecture
  )
    throw new Error(
      `Codex component ${component.id} is for ${component.nodePlatform}/${component.architecture}, not ${process.platform}/${process.arch}.`,
    );
  const paths = componentPaths(dirname(directory), component);
  if (paths.directory !== resolve(directory))
    throw new Error(
      `Codex component directory must end in its immutable id ${component.id}.`,
    );
  const [executable, codeModeHost] = await Promise.all([
    verifyFile(paths.executable, component.executable, "Codex executable"),
    verifyFile(
      paths.codeModeHost,
      component.codeModeHost,
      "Codex code-mode host",
    ),
  ]);
  const cliVersion = await probeCodexVersion(paths.executable);
  if (cliVersion !== component.cliVersion)
    throw new Error(
      `Codex version ${cliVersion} does not match approved component ${component.cliVersion}.`,
    );
  return { component, executable, codeModeHost };
}

export async function inspectExternalCandidate(executablePath) {
  const executable = resolve(executablePath);
  const codeModeHost = join(dirname(executable), "codex-code-mode-host");
  const [version, executableStat, helperStat, executableDigest, helperDigest] =
    await Promise.all([
      probeCodexVersion(executable),
      stat(executable),
      stat(codeModeHost),
      sha256(executable),
      sha256(codeModeHost),
    ]);
  return {
    cliVersion: version,
    nodePlatform: process.platform,
    architecture: process.arch,
    executable: {
      path: executable,
      sha256: executableDigest,
      bytes: executableStat.size,
    },
    codeModeHost: {
      path: codeModeHost,
      sha256: helperDigest,
      bytes: helperStat.size,
    },
  };
}

export async function installQualifiedComponent(
  sourceExecutable,
  component,
  managedRoot = defaultManagedCodexRoot(),
  receiptPath = qualificationEvidencePath(component),
  { renameDirectory = rename } = {},
) {
  const candidate = await inspectExternalCandidate(sourceExecutable);
  if (
    candidate.cliVersion !== component.cliVersion ||
    candidate.executable.sha256 !== component.executable.sha256 ||
    (component.executable.bytes !== undefined &&
      candidate.executable.bytes !== component.executable.bytes) ||
    candidate.codeModeHost.sha256 !== component.codeModeHost.sha256 ||
    candidate.codeModeHost.bytes !== component.codeModeHost.bytes
  )
    throw new Error(
      `External candidate does not match qualified component ${component.id}.`,
    );
  const receipt = await verifyQualificationReceipt(receiptPath, component);
  await mkdir(managedRoot, { recursive: true, mode: 0o700 });
  const destination = componentPaths(managedRoot, component);
  try {
    const installed = await verifyComponentDirectory(
      destination.directory,
      component,
    );
    await verifyInstalledQualificationReceipt(destination.directory, component);
    return installed;
  } catch (error) {
    let destinationExists = true;
    try {
      await stat(destination.directory);
    } catch (statError) {
      if (statError?.code !== "ENOENT") throw error;
      // The immutable destination is absent, so installation may proceed.
      destinationExists = false;
    }
    if (destinationExists)
      throw new Error(
        `Managed Codex component ${component.id} already exists but conflicts with the qualified identity; it was left unchanged.`,
        { cause: error },
      );
  }
  const temporary = `${destination.directory}.installing-${process.pid}`;
  await rm(temporary, { recursive: true, force: true });
  try {
    await mkdir(temporary, { recursive: true, mode: 0o700 });
    await Promise.all([
      copyFile(
        candidate.executable.path,
        join(temporary, component.executable.filename),
      ),
      copyFile(
        candidate.codeModeHost.path,
        join(temporary, component.codeModeHost.filename),
      ),
    ]);
    await Promise.all([
      chmod(join(temporary, component.executable.filename), 0o755),
      chmod(join(temporary, component.codeModeHost.filename), 0o755),
    ]);
    await writeFile(
      join(temporary, "qualification.json"),
      `${JSON.stringify(receipt, null, 2)}\n`,
      { mode: 0o600 },
    );
    await renameDirectory(temporary, destination.directory);
  } catch (error) {
    await rm(temporary, { recursive: true, force: true });
    try {
      const installed = await verifyComponentDirectory(
        destination.directory,
        component,
      );
      await verifyInstalledQualificationReceipt(
        destination.directory,
        component,
      );
      return installed;
    } catch {
      throw error;
    }
  }
  const installed = await verifyComponentDirectory(
    destination.directory,
    component,
  );
  await verifyInstalledQualificationReceipt(destination.directory, component);
  return installed;
}
